def tf(paden,f):
    out=[]
    for d in paden:
        nums=[float(v) for v in re.findall(r'-?\d+\.?\d*',d)];cmds=re.findall(r'[MLQC]',d)
        it=iter(nums);pts=[f(x,y) for x,y in zip(it,it)]
        # opnieuw opbouwen: M x y, Q x y x y ...
        s='';k=0
        for c in cmds:
            n={'M':1,'L':1,'Q':2,'C':3}[c]
            s+=c+' '.join('%.1f %.1f'%pts[k+j] for j in range(n))+' ';k+=n
        out.append(s.strip())
    return out
